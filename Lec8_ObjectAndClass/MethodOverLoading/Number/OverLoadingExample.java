package lec8_ObjectandClasses.MethodOverloading.Number;
//Overloading theo number(so luong tham so)
public class OverLoadingExample {

    public static int add(int a, int b) {
        return a + b;
    }

    public static int add(int a, int b, int c) {
        return a + b + c;
    }

}
